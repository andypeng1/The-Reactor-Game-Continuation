def roll(bs):
    h = 0
    for b in bs:
        h = (h * 31 + b) & 0x7FFFFFFF
    return "%08x" % h


def chunks(bs, n=64):
    return [bs[i:i + n] for i in range(0, len(bs), n)]


fail = 0
for d in DOCS:
    raw = io.open(d["path"], "rb").read()
    print("=== %s ===" % d["name"])
    print("  baseline %d %s   (module's previous image: %d %s)"
          % (len(raw), roll(raw), d["base_len"], d["base_hash"]))
    if len(raw) != d["base_len"] or roll(raw) != d["base_hash"]:
        print("  *** disk is not at the pre-repair baseline -- ABORT ***")
        fail = 1
        continue

    delta = bytes.fromhex(d["hex"])
    if len(delta) != d["delta_len"] or roll(delta) != d["delta_hash"]:
        print("  *** delta is %d bytes hashing %s, module says %d/%s -- ABORT (transcription) ***"
              % (len(delta), roll(delta), d["delta_len"], d["delta_hash"]))
        fail = 1
        continue
    ck = chunks(delta)
    print("  delta: %d chunks of 64, all reproduced from hex (first %s last %s)"
          % (len(ck), ck[0][:8].hex(), ck[-1][-4:].hex()))

    out = raw + delta            # the mirror is the module image, and this delta only appends
    ok = len(out) == d["want_len"] and roll(out) == d["want_hash"]
    print("  candidate %d %s   (module says %d %s)  %s"
          % (len(out), roll(out), d["want_len"], d["want_hash"], "PASS" if ok else "*** FAIL ***"))
    if not ok:
        fail = 1
        continue
    io.open(d["path"] + ".bakdr33", "wb").write(raw)
    io.open(d["path"], "wb").write(out)
    print("  written: %d -> %d (+%d)" % (len(raw), len(out), len(out) - len(raw)))

