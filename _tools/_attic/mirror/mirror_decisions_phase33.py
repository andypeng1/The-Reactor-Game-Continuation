def roll(bs):
    h = 0
    for b in bs:
        h = (h * 31 + b) & 0x7FFFFFFF
    return "%08x" % h


def decode(name, text):
    lines = text.split()
    for i, ln in enumerate(lines, 1):
        if len(ln) % 2:
            print("*** %s line %d has an odd hex digit count -- ABORT ***" % (name, i))
            sys.exit(1)
    out = bytes.fromhex("".join(lines))
    print("%s: %d lines, %d bytes" % (name, len(lines), len(out)))
    return out


def verify_chunks(bs, ref, what):
    """Assert every 64-byte chunk against the hash the ModuleScript reported for it."""
    refs = [x.split(":") for x in ref.split()]
    for i, rf in enumerate(refs, 1):
        want_len, want_hash = int(rf[2]), rf[1]
        chunk = bs[(i - 1) * 64: (i - 1) * 64 + want_len]
        if len(chunk) != want_len or roll(chunk) != want_hash:
            print("*** %s chunk %d: got len=%d hash=%s, module says len=%d hash=%s -- ABORT ***"
                  % (what, i, len(chunk), roll(chunk), want_len, want_hash))
            sys.exit(1)
    print("%s: %d chunks verified against the module's own hashes" % (what, len(refs)))


