def extract(path: Path) -> str:
    src = path.read_text(encoding="utf-8")
    m = re.search(r"^local function driveStep\(tempF, isRunning, dt\)\n.*?^end$", src, re.S | re.M)
    if not m:
        sys.exit("could not find driveStep in %s -- did it get renamed, or did its "
                 "signature change? The regex is anchored on `(tempF, isRunning, dt)` "
                 "on purpose: the third parameter is the measured step, and a copy "
                 "of this function without it is the version that ran 18 per cent "
                 "long." % path)
    body = m.group(0)
    # The extraction is only trustworthy if it is complete. A brace/paren count
    # is not a parser, but it fails loudly on the one mistake that matters here:
    # a truncated body that still compiles because the tail happened to close it.
    for open_c, close_c in (("(", ")"), ("{", "}")):
        if body.count(open_c) != body.count(close_c):
            sys.exit("extracted driveStep is unbalanced on %r: %d vs %d"
                     % (open_c, body.count(open_c), body.count(close_c)))
    if not body.rstrip().endswith("end"):
        sys.exit("extracted driveStep does not end in `end`")
    return body


