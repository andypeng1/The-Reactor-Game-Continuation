"""Build a harness that runs the SHIPPED driveStep against a simulated core.

Why a builder and not a hand-written test file: a test that is a COPY of the
function under test passes against the copy, which is the one version that is
never the one that ships. This extracts `driveStep` out of
_tools/TRG_original_recorder.luau by text, wraps it in mocks, and prints the
result -- so what runs is the same bytes that get injected, and a change to the
recorder is a change to the test.

    python _tools/build_driver_test.py
    # writes _tools/_driver_states.luau, then run it:
    #   in Studio, execute_luau the file contents; or read it and run it anywhere
    #   Luau runs, because the harness touches no Roblox API at all.

THE SCENARIOS RUN IN BOTH CONFIGURATIONS, AND THAT IS THE POINT. `D7` has the
operator pressing the shutdown lever himself (`D7: 我自己手动关`), so the LIVE
setting is `Config.DrivePressControls = false` and the driver never presses
anything. The press path is not deleted -- §1.4 forbids removing a capability
without a replacement -- so it stays in the shipped function behind that flag,
and a scenario opts into it with `{ pressControls = true }`. Every scenario
below therefore states which configuration it is about, and the suite covers
both rather than the one that happens to be shipping.

The scenarios are the ways the driver can end, and every one of them is a path
out of the state machine, because a state machine is only as good as its exits:

  S1  hot core, driver holds the controls -> presses, ends `shut_down`   (press)
  S2  hot core, the shut switch INERT     -> one press, ends `shut_down` (press)
  S3  cold core, driver holds the controls-> lights it, ends `shut_down` (press)
  S4  no temperature readout at all       -> presses nothing, stays `arming`
  S5  cold at inject, operator lights it  -> waits, then ends `watching` (live)
  S6  the core dips on its own mid-hold   -> one press, ends `shut_down` (press)
  S7  a slow loop is measured, not assumed-> the press lands on time     (press)
  S8  a slow FIRST poll fakes nothing     -> one press, ends `shut_down` (press)
  S9  the operator presses, game confirms -> ends `shut-confirmed`      (live)
  S10 hot core at inject, no press ever   -> stays `watching`, nothing pressed
  S11 the MACHINE ROOM melts down         -> names it, nothing pressed  (live)

Two of these are scars. S3 found a real bug on 2026-09-26: with the core cold at
inject, the driver lit it and then parked in `waiting_up` waiting for a `sawDown`
the cold path never produces, so the run would have recorded a healthy reactor
until the sample cap instead of the flow it was injected for. The fix then was
to light the core earlier; under the live setting it is not lit at all, because
the operator does that himself and the core can only be switched ONCE.

S2 is the other scar, and it is a scar about retries. The driver used to walk
down its candidate list, pressing the next switch whenever a press proved inert,
so S2 used to expect two presses. With one attempt available, a second press is
a second spent action, and the run now ends naming the control it pressed. The
scenario is kept precisely because it pins that: `ShutFallback` is on the list,
it is never pressed, and a driver that starts walking again fails here.

S10 is the newest, and it is the one the live run is actually protected by. It
is deliberately the dullest scenario here -- a hot core, nothing happening, three
hundred seconds of nothing happening -- because the live driver s one job is to
keep not pressing, and every failure mode that matters is a press.
"""

