def slice_between(src: str, start_marker: str, end_marker: str, what: str) -> str:
    start = src.find(start_marker)
    if start < 0:
        sys.exit("could not find the start of %s" % what)
    end = src.find(end_marker, start)
    if end < 0:
        sys.exit("could not find the end of %s" % what)
    return src[start:end]


def extract_key_for_label(src: str) -> str:
    m = re.search(r"^local function keyForLabel\(label, seen\)\n.*?^end$", src, re.S | re.M)
    if not m:
        sys.exit("could not find keyForLabel -- did it get rewritten?")
    return m.group(0)


def main(argv) -> int:
    # The two paths are overridable so that selftest_gui.py can point the very
    # same extraction at a deliberately broken copy of the recorder.  A mutation
    # test against a different builder would be testing the builder.
    src_path = Path(argv[1]) if len(argv) > 1 else RECORDER
    out_path = Path(argv[2]) if len(argv) > 2 else OUT
    src = src_path.read_text(encoding="utf-8")

    state_block = slice_between(
        src,
        "-- ==================== PLAYER GUI: STATE",
        "-- ==================== READOUT DISCOVERY",
        "the player-GUI state block")
    fn_block = slice_between(
        src,
        "-- ========================== PLAYER GUI ====",
        "-- ========================== FLOW ==",
        "the player-GUI function block")

    for name, block in (("state", state_block), ("functions", fn_block)):
        for open_c, close_c in (("(", ")"), ("{", "}")):
            if block.count(open_c) != block.count(close_c):
                sys.exit("the %s block is unbalanced on %r: %d vs %d"
                         % (name, open_c, block.count(open_c), block.count(close_c)))

    for needle in ("local function ensureGuiRoot", "local function buildGui",
                   "local function readGui", "local function flagReaderFor"):
        if needle not in fn_block:
            sys.exit("the function block is missing %r" % needle)
    for needle in ("local guiRecords, guiDirty", "local isOwnGui"):
        if needle not in state_block:
            sys.exit("the state block is missing %r" % needle)

    key_fn = extract_key_for_label(src)

    body = HEAD + state_block + "\n" + key_fn + "\n\n" + fn_block + "\n" + TAIL
    out_path.write_text(body, encoding="utf-8", newline="\n")
    raw = out_path.read_bytes()
    print("wrote %s" % out_path)
    print("  lines %d  bytes %d" % (raw.decode("utf-8").count("\n"), len(raw)))
    print("  extracted state lines %d  function lines %d"
          % (state_block.count("\n") + 1, fn_block.count("\n") + 1))
    print("  backslash bytes %d  (must be 0: the editor decodes escapes once)"
          % raw.count(0x5C))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
