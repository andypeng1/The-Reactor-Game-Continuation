"""Prove the player-GUI reader, which is the one reader no other test can reach.

Everything else in the recorder points at Workspace, and Workspace is the same
object for the server and for every client. PlayerGui is not: it exists only in
the client that owns it and nothing about it replicates, so this reader can only
ever run inside an injected script -- which means it gets one shot per shift and
no second attempt to notice it was wrong.

There are three ways for it to be wrong and only one of them is loud:

  * It reads the wrong property. Measured in Studio on 2026-09-27: ScreenGui
    answers Enabled and THROWS on Visible, Frame answers Visible and THROWS on
    Enabled, and no class answers both. Asking the wrong one raises, readGui
    raises with it, pollOnce raises, and the run records NOTHING -- for the whole
    shift, from a subsystem that was supposed to be additive.
  * It records the recorder. The panel this script builds is parented to
    PlayerGui and rewrites its text four times a second. A chatter guard would
    eventually condemn it, so the file would carry a NOISY verdict about a label
    the recorder owns. Silent, and it looks like a finding about the game.
  * It reads the object's own flag and calls it what the player can see. That is
    deliberate and is argued in the source; the ScreenGui's Enabled is what
    closes the gap, so this harness pins Enabled as well.

So the objects here are mocked with the MEASURED behaviour, not a convenient
one: Visible and Enabled are not fields but metatable arms that raise when asked
for on the wrong class, exactly as the engine does. A mock that answered nil
instead would let a wrong reader pass this file and die in the game.

Both regions and `keyForLabel` are EXTRACTED from the shipped recorder by text.
Nothing is re-declared here, because a harness that agrees with its own copy of
the state proves nothing about the state that ships.

    python _tools/build_gui_test.py
    /d/Lua/5.1/lua.exe -e "print(assert(loadfile('_tools/_gui_states.luau'))())"
"""

